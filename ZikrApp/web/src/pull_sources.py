"""Pull authentic Quran and hadith text for every reference used in the app.
Quran: quran-json (Uthmani text from QuranEnc / King Fahd Complex, Saheeh International
English, Tanzil transliteration). Hadith: sunnah.com dataset (npm package "hadith").
Usage: pull_sources.py <web dir> <quran-json dist dir> <hadith.db> <out sources.js>"""
import json, re, sqlite3, sys, os
web, qdir, dbp, out = sys.argv[1:5]
texts = "".join(open(os.path.join(web, f), encoding="utf8").read() for f in ["reflections.js", "more_topics.js", "hadith.js"])

# ---------- Quran ----------
chap = {}
def surah(n):
    if n not in chap: chap[n] = json.load(open(os.path.join(qdir, "chapters", "en", f"{n}.json"), encoding="utf8"))
    return chap[n]
verse_keys = set(f"{s}:{a}" + (f"-{b}" if b else "") for s, a, b in re.findall(r'ref: "[^"]*?(\d+):(\d+)(?:[–-](\d+))?', texts))
verse_keys |= {"2:255", "112:1-4", "113:1-5", "114:1-6", "7:180"}
QURAN = {}
for key in sorted(verse_keys):
    s, rng = key.split(":"); a, _, b = rng.partition("-"); s, a = int(s), int(a); b = int(b) if b else a
    d = surah(s); vs = [v for v in d["verses"] if a <= v["id"] <= b]
    multi = len(vs) > 1
    QURAN[key] = {
        "ar": " ".join(v["text"] + (f" ﴿{v['id']}﴾" if multi else "") for v in vs),
        "en": " ".join((f"({v['id']}) " if multi else "") + v["translation"] for v in vs),
        "tl": " ".join(v["transliteration"] for v in vs),
        "surah": d["transliteration"], "ref": f"{d['transliteration']} {s}:{a}" + (f"–{b}" if b != a else ""),
    }

# ---------- Hadith ----------
COLL = {"Sahih al-Bukhari": (1, "bukhari"), "Sahih Muslim": (2, "muslim"), "Sunan Abi Dawud": (10, "abudawud"),
        "Jami‘ at-Tirmidhi": (30, "tirmidhi"), "Sunan Ibn Majah": (38, "ibnmajah"), "Al-Adab al-Mufrad": (115, "adab"),
        "Sunan an-Nasa'i": (3, "nasai")}
db = sqlite3.connect(dbp); cur = db.cursor()
STOP = set("that this with from have what when your they them their there which would will were then than said says said: allah messenger prophet the and for".split())
words = lambda t: {w for w in re.findall(r"[a-z]{4,}", t.lower()) if w not in STOP}
CIDS = sorted({v[0] for v in COLL.values()})
EN = {r[0]: r[1:] for r in cur.execute(f"select arabic_urn, narrator_prefix, content, grades from hadith_en where collection_id in ({','.join(map(str, CIDS))})")}
AR = {}
for urn, cid, dn, content, grades in cur.execute(f"select urn, collection_id, display_number, content, grades from hadith where collection_id in ({','.join(map(str, CIDS))})"):
    e = EN.get(urn, (None, None, None))
    AR.setdefault(cid, []).append((dn, content, grades, e[0], e[1], e[2]))
WORDCACHE = {}
def rows(cid, num=None):
    if num is None: return AR.get(cid, [])
    return [r for r in AR.get(cid, []) if r[0] == str(num) or r[0].startswith(f"{num} ")]
def grade(g1, g2):
    for g in (g2, g1):
        try:
            j = json.loads(g) if g else None
            if j: return "; ".join(f"{x.get('grade','').strip()}" + (f" ({x.get('graded_by','').strip()})" if x.get('graded_by') else "") for x in j)[:120]
        except Exception:
            if g: return str(g)[:120]
    return ""
HAD, report = {}, []
for ref, mine in re.findall(r'ref: "([^"]+?) (\d+)", text: "((?:[^"\\]|\\.)*)"', texts) and [(f"{c} {n}", t) for c, n, t in re.findall(r'ref: "([^"]+?) (\d+)", text: "((?:[^"\\]|\\.)*)"', texts)] or []:
    if ref in HAD: continue
    cname, num = ref.rsplit(" ", 1)
    if cname not in COLL: report.append(f"SKIP unknown collection: {ref}"); continue
    cid, slug = COLL[cname]; mw = words(mine)
    def score(r):
        k = id(r)
        if k not in WORDCACHE: WORDCACHE[k] = words((r[3] or "") + " " + (r[4] or ""))
        return len(mw & WORDCACHE[k]) / max(1, len(mw))
    cands = rows(cid, num); best = max(cands, key=score) if cands else None
    # Keep the cited number; only choose between its sub-narrations (a, b, c...).
    note = "" if (best and score(best) >= 0.3) else f"REVIEW {ref}: match {score(best) if best else 0:.2f} (wording differs; check)"
    if not best: report.append(f"NOT FOUND {ref}"); continue
    dn = best[0].replace(" ", "")
    HAD[ref] = {"ref": f"{cname} {best[0]}", "url": f"https://sunnah.com/{slug}:{dn}", "ar": (best[1] or "").strip(),
                "narrator": (best[3] or "").strip(), "en": re.sub(r"\s+", " ", (best[4] or "")).strip(), "grade": grade(best[2], best[5]),
                "match": round(score(best), 2)}
    if note: report.append(note)
open(out, "w", encoding="utf8").write(
    "/* Generated by pull_sources.py from authentic sources. Do not edit by hand.\n"
    "   Quran: Uthmani text (QuranEnc, King Fahd Complex), Saheeh International, Tanzil transliteration.\n"
    "   Hadith: sunnah.com collection data (Arabic, English, grading). */\n"
    f"const QURAN_SRC = {json.dumps(QURAN, ensure_ascii=False)};\nconst HADITH_SRC = {json.dumps(HAD, ensure_ascii=False)};\n")
print(f"verses {len(QURAN)}, hadith {len(HAD)}")
print("\n".join(report) or "all hadith matched by reference")
print("lowest matches:", sorted((v['match'], k) for k, v in HAD.items())[:8])
